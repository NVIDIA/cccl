  REQUIRE(std::string(THRUST_PP_STRINGIZE(THRUST_PP_EXPAND(hello world))) == "hello world");

  REQUIRE(std::string(THRUST_PP_STRINGIZE(THRUST_PP_EXPAND(hello  world))) == "hello world");

  REQUIRE(std::string(THRUST_PP_STRINGIZE(THRUST_PP_EXPAND( hello  world))) == "hello world");

