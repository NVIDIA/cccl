def _scikit_build_wheel_config() -> dict:
    with (PACKAGE_ROOT / "pyproject.toml").open("rb") as stream:
        return tomllib.load(stream)["tool"]["scikit-build"]["wheel"]


def _project_dependencies() -> list[str]:
    with (PACKAGE_ROOT / "pyproject.toml").open("rb") as stream:
        return tomllib.load(stream)["project"]["dependencies"]


def _project_optional_dependencies() -> dict[str, list[str]]:
    with (PACKAGE_ROOT / "pyproject.toml").open("rb") as stream:
        return tomllib.load(stream)["project"]["optional-dependencies"]


def _installed_wheel_files() -> tuple[str, ...]:
    try:
        distribution = importlib.metadata.distribution("cuda-coop")
    except importlib.metadata.PackageNotFoundError:
        pytest.skip("cuda-coop is not installed; wheel checks need the built wheel")
    direct_url = distribution.read_text("direct_url.json")
    if direct_url is not None and json.loads(direct_url).get("dir_info", {}).get(
        "editable", False
    ):
        pytest.skip("cuda-coop is editable; wheel checks need the built wheel")
    spec = importlib.util.find_spec("cuda.coop._core")
    imported = Path(spec.origin).resolve()
    installed = Path(
        str(distribution.locate_file("cuda/coop/_core/__init__.py"))
    ).resolve()
    if imported != installed:
        pytest.skip("cuda.coop does not import from the installed cuda-coop wheel")
    # Exclude installer-generated bytecode; callers scope distribution metadata
    # to the package subtree they are auditing.
    return tuple(
        file.as_posix()
        for file in distribution.files or ()
        if "__pycache__" not in file.parts and file.suffix != ".pyc"
    )


def test_wheel_package_map_owns_the_complete_cuda_coop_root():
    assert _scikit_build_wheel_config()["packages"] == _EXPECTED_PACKAGE_MAP


def test_typing_extensions_is_a_direct_runtime_dependency():
    assert "typing_extensions>=4.12.0" in _project_dependencies()


def test_cuda_pathfinder_is_a_direct_runtime_dependency():
    assert "cuda-pathfinder>=1.2.3" in _project_dependencies()


def test_backend_extras_are_dependency_only_and_use_public_names():
    extras = _project_optional_dependencies()

    assert {"cu12", "cu13"} <= set(extras)
    assert extras["cu13"] == [
        "cuda-bindings>=13.0.0,<14.0.0",
        "cuda-toolkit[nvrtc,nvjitlink,cudart,nvcc,nvvm]==13.*",
    ]
    assert extras["cutlass"] == [
        "cuda-coop[cu13]",
        "nvidia-cutlass-dsl>=4.8,<5",
    ]
    assert extras["cutlass-cu12"] == [
        "cuda-coop[cu12]",
        "nvidia-cutlass-dsl>=4.8,<5",
    ]
    assert extras["cutlass-cu13"] == extras["cutlass"]
    assert extras["numba-cuda-mlir"] == [
        "cuda-coop[cu13]",
        "numba-cuda-mlir[cu13]>=0.5.0",
    ]
    assert extras["numba-cuda-mlir-cu12"] == [
        "cuda-coop[cu12]",
        "numba-cuda-mlir[cu12]>=0.5.0",
    ]
    assert extras["numba-cuda-mlir-cu13"] == [
        "cuda-coop[cu13]",
        "numba-cuda-mlir[cu13]>=0.5.0",
    ]


