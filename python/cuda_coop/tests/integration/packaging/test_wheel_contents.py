def test_wheel_metadata_is_reproducible_and_python_minor_independent():
    wheel = _scikit_build_wheel_config()

    assert wheel["py-api"] == "py3"
    assert wheel["reproducible"] is True
    assert wheel["license-files"] == []
    assert wheel["force-include"] == {
        "../../LICENSE": "${SKBUILD_METADATA_DIR}/licenses/LICENSE",
        "../../cub/LICENSE.TXT": "${SKBUILD_METADATA_DIR}/licenses/cub/LICENSE.TXT",
        "../../cudax/LICENSE.TXT": "${SKBUILD_METADATA_DIR}/licenses/cudax/LICENSE.TXT",
        "../../libcudacxx/LICENSE.TXT": (
            "${SKBUILD_METADATA_DIR}/licenses/libcudacxx/LICENSE.TXT"
        ),
        "../../thrust/LICENSE": "${SKBUILD_METADATA_DIR}/licenses/thrust/LICENSE",
    }


def test_installed_wheel_ships_supported_python_payloads():
    installed = set(_installed_wheel_files())

    assert {
        "cuda/coop/__init__.py",
        "cuda/coop/_core/__init__.py",
        "cuda/coop/_core/_auto_registration.py",
        "cuda/coop/_headers/__init__.py",
        "cuda/coop/cutlass/__init__.py",
        "cuda/coop/numba_mlir/__init__.py",
    } <= installed


def test_installed_wheel_ships_public_typing_artifacts():
    installed = set(_installed_wheel_files())

    assert set(_TYPING_ARTIFACTS) <= installed


def test_installed_wheel_uses_only_private_qualified_scope_packages():
    installed = set(_installed_wheel_files())

    assert {
        "cuda/coop/cutlass/_block/__init__.py",
        "cuda/coop/cutlass/_warp/__init__.py",
        "cuda/coop/numba_mlir/_block/__init__.py",
        "cuda/coop/numba_mlir/_warp/__init__.py",
    } <= installed
    assert not any(
        path.startswith(prefix)
        for path in installed
        for prefix in _RETIRED_PUBLIC_SCOPE_PREFIXES
    )


def test_installed_pep561_markers_are_empty():
    _installed_wheel_files()
    distribution = importlib.metadata.distribution("cuda-coop")

    for marker in (
        artifact for artifact in _TYPING_ARTIFACTS if artifact.endswith("py.typed")
    ):
        path = Path(str(distribution.locate_file(marker)))
        assert path.read_bytes() == b""


def test_installed_wheel_ships_private_cccl_headers():
    installed = set(_installed_wheel_files())

    assert {
        "cuda/coop/_headers/include/cub/block/block_reduce.cuh",
        "cuda/coop/_headers/include/cuda/experimental/coop.cuh",
    } <= installed


def test_installed_wheel_ships_component_licenses():
    licenses = {
        path for path in _installed_wheel_files() if ".dist-info/licenses/" in path
    }

    assert {path.rsplit("/licenses/", 1)[1] for path in licenses} == {
        "LICENSE",
        "cub/LICENSE.TXT",
        "cudax/LICENSE.TXT",
        "libcudacxx/LICENSE.TXT",
        "thrust/LICENSE",
    }
